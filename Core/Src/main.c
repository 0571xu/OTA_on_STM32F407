/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
	/* 向量表必须指向本镜像实际链接的槽：A 版 0x08020000，B 版 0x08060000 */
	SCB->VTOR = APP_IMAGE_BASE;
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_USART1_UART_Init();
  MX_SPI1_Init();
  MX_IWDG_Init();
  MX_CAN1_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */

	/* 编译时间戳：确认板子上跑的到底是不是刚烧进去的这一版 */
	boot_log("[boot] build " __DATE__ " " __TIME__ "\r\n");

	GPIO_InitTypeDef GPIO_InitStructure;
	GPIO_InitStructure.Pin = GPIO_PIN_1;
	GPIO_InitStructure.Mode = GPIO_MODE_OUTPUT_PP;
	GPIO_InitStructure.Speed = GPIO_SPEED_FREQ_MEDIUM;
	HAL_GPIO_Init(GPIOA, &GPIO_InitStructure);

	/*
	 * 启动初始化：
	 *   1. 元数据缺失时用当前运行槽建立第一份配置；
	 *   2. Bootloader 若做过回退，这里修正 active_slot 并标记失败槽；
	 *   3. 注意：不清 trial_pending，试运行确认由心跳任务在健康运行 5s 后完成。
	 */
	ota_app_boot_init(APP_IMAGE_BASE);
	boot_log("[boot] 6 meta ok\r\n");

	/*
	 * F103 镜像暂存区自测：擦 S4 + 三处写图案 + 读回比对，耗时约 1~2 秒。
	 * 它会擦掉 S4 里已暂存的镜像，正式使用前把 OTA_STAGING_SELFTEST_ON_BOOT 改成 0。
	 */
#if OTA_STAGING_SELFTEST_ON_BOOT
	{
		char stg_line[48];
		int  stg_rc = ota_staging_selftest();

		(void)snprintf(stg_line, sizeof(stg_line), "[stg] selftest %s rc=%d\r\n",
		               (stg_rc == 0) ? "ok" : "FAIL", stg_rc);
		boot_log(stg_line);
	}
#endif

	/*
	 * CAN 初始化放到任务里执行：
	 * CAN 外设异常（无收发器、波特率配错、邮箱卡死）不应该把整个系统拖死在启动阶段，
	 * 否则表现就是"Bootloader 反复重启、APP 一句日志都看不到"。
	 */
	if (xTaskCreate(can_start_task, "canInit", 256, NULL, 3, NULL) != pdPASS)
	{
		boot_log("[boot] can task create fail\r\n");
	}
	boot_log("[boot] 7 start scheduler\r\n");

  /* USER CODE END 2 */

  /* Call init function for freertos objects (in cmsis_os2.c) */
  MX_FREERTOS_Init();

  /* Start scheduler */
  osKernelStart();

  /* We should never get here as control is now taken by the scheduler */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
	while (1)
	{
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	}
  /* USER CODE END 3 */
}

/**
  * @brief System Clock Configuration
  * @retval None
  */
void SystemClock_Config(void)
{
  RCC_OscInitTypeDef RCC_OscInitStruct = {0};
  RCC_ClkInitTypeDef RCC_ClkInitStruct = {0};

  /** Configure the main internal regulator output voltage
  */
  __HAL_RCC_PWR_CLK_ENABLE();
  __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE1);

  /** Initializes the RCC Oscillators according to the specified parameters
  * in the RCC_OscInitTypeDef structure.
  */
  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_LSI|RCC_OSCILLATORTYPE_HSE;
  RCC_OscInitStruct.HSEState = RCC_HSE_ON;
  RCC_OscInitStruct.LSIState = RCC_LSI_ON;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_HSE;
  RCC_OscInitStruct.PLL.PLLM = 8;
  RCC_OscInitStruct.PLL.PLLN = 336;
  RCC_OscInitStruct.PLL.PLLP = RCC_PLLP_DIV2;
  RCC_OscInitStruct.PLL.PLLQ = 4;
  if (HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    Error_Handler();
  }

  /** Initializes the CPU, AHB and APB buses clocks
  */
  RCC_ClkInitStruct.ClockType = RCC_CLOCKTYPE_HCLK|RCC_CLOCKTYPE_SYSCLK
                              |RCC_CLOCKTYPE_PCLK1|RCC_CLOCKTYPE_PCLK2;
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV4;
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV2;

  if (HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_5) != HAL_OK)
  {
    Error_Handler();
  }
}

